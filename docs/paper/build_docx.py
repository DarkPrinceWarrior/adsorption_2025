from docx.oxml import parse_xml as _parse_xml

M_NS = 'xmlns:m="http://schemas.openxmlformats.org/officeDocument/2006/math"'


def mr(t: str, plain: bool = False) -> str:
    sty = '<m:rPr><m:sty m:val="p"/></m:rPr>' if plain else ""
    return f'<m:r>{sty}<m:t xml:space="preserve">{t}</m:t></m:r>'


def mfrac(num: str, den: str) -> str:
    return f"<m:f><m:num>{num}</m:num><m:den>{den}</m:den></m:f>"


def msub(base: str, sub: str) -> str:
    return f"<m:sSub><m:e>{base}</m:e><m:sub>{sub}</m:sub></m:sSub>"


def msup(base: str, sup: str) -> str:
    return f"<m:sSup><m:e>{base}</m:e><m:sup>{sup}</m:sup></m:sSup>"


def msubsup(base: str, sub: str, sup: str) -> str:
    return f"<m:sSubSup><m:e>{base}</m:e><m:sub>{sub}</m:sub><m:sup>{sup}</m:sup></m:sSubSup>"


def mpar(inner: str, beg: str = "(", end: str = ")") -> str:
    return (f'<m:d><m:dPr><m:begChr m:val="{beg}"/><m:endChr m:val="{end}"/></m:dPr>'
            f"<m:e>{inner}</m:e></m:d>")


def mhat(base: str) -> str:
    return f'<m:acc><m:accPr><m:chr m:val="&#770;"/></m:accPr><m:e>{base}</m:e></m:acc>'


def msum(sub: str, body: str) -> str:
    return ('<m:nary><m:naryPr><m:chr m:val="&#8721;"/><m:limLoc m:val="undOvr"/>'
            '<m:supHide m:val="1"/></m:naryPr>'
            f"<m:sub>{sub}</m:sub><m:sup/><m:e>{body}</m:e></m:nary>")


def p_rich(segments, *, indent: bool = True, align=WD_ALIGN_PARAGRAPH.JUSTIFY,
           size: int = 12, space_before: int = 0, space_after: int = 0):
    par = doc.add_paragraph()
    par.alignment = align
    pf = par.paragraph_format
    if indent:
        pf.first_line_indent = Cm(1.25)
    pf.space_before = Pt(space_before)
    pf.space_after = Pt(space_after)
    for seg in segments:
        if isinstance(seg, str):
            run = par.add_run(seg)
            run.font.size = Pt(size)
        else:
            par._p.append(_parse_xml(f"<m:oMath {M_NS}>{seg[1]}</m:oMath>"))
    return par


def equation(inner: str, *, space_before: int = 4, space_after: int = 4):
    par = doc.add_paragraph()
    par.alignment = WD_ALIGN_PARAGRAPH.CENTER
    par.paragraph_format.space_before = Pt(space_before)
    par.paragraph_format.space_after = Pt(space_after)
    par._p.append(_parse_xml(f"<m:oMathPara {M_NS}><m:oMath>{inner}</m:oMath></m:oMathPara>"))
    return par


