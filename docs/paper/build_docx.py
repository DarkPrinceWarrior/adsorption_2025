def p(text: str, *, indent: bool = True, align=WD_ALIGN_PARAGRAPH.JUSTIFY,
      bold: bool = False, italic: bool = False, size: int = 12,
      space_before: int = 0, space_after: int = 0, line15: bool = True):
    par = doc.add_paragraph()
    par.alignment = align
    pf = par.paragraph_format
    if indent:
        pf.first_line_indent = Cm(1.25)
    pf.space_before = Pt(space_before)
    pf.space_after = Pt(space_after)
    if not line15:
        pf.line_spacing_rule = WD_LINE_SPACING.SINGLE
    run = par.add_run(text)
    run.bold = bold
    run.italic = italic
    run.font.size = Pt(size)
    return par


def h1(text: str):
    par = p(text.upper(), indent=False, align=WD_ALIGN_PARAGRAPH.CENTER, bold=True,
            size=12, space_before=14, space_after=8)
    par.paragraph_format.keep_with_next = True
    return par


def h2(text: str):
    par = p(text, indent=False, bold=True, size=12, space_before=10, space_after=4,
            align=WD_ALIGN_PARAGRAPH.LEFT)
    par.paragraph_format.keep_with_next = True
    return par


def figure(filename: str, caption: str, width_cm: float = 16.0):
    path = os.path.join(FIG, filename)
    par = doc.add_paragraph()
    par.alignment = WD_ALIGN_PARAGRAPH.CENTER
    par.paragraph_format.space_before = Pt(8)
    run = par.add_run()
    run.add_picture(path, width=Cm(width_cm))
    cap = p(caption, indent=False, align=WD_ALIGN_PARAGRAPH.CENTER, size=11,
            space_after=10, line15=False)
    return cap


def shade(cell, color: str):
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:fill"), color)
    tcPr.append(shd)


def table(caption: str, *, headers, rows, col_widths=None, font_size: int = 10,
          align_first_left: bool = True):
    p("Таблица " + caption, indent=False, size=11, space_before=10, space_after=4,
      align=WD_ALIGN_PARAGRAPH.LEFT, line15=False)
    tbl = doc.add_table(rows=1 + len(rows), cols=len(headers))
    tbl.style = "Table Grid"
    tbl.alignment = WD_TABLE_ALIGNMENT.CENTER
    for j, head in enumerate(headers):
        cell = tbl.rows[0].cells[j]
        cell.text = ""
        par = cell.paragraphs[0]
        par.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = par.add_run(head)
        run.bold = True
        run.font.size = Pt(font_size)
        par.paragraph_format.line_spacing_rule = WD_LINE_SPACING.SINGLE
        par.paragraph_format.space_after = Pt(2)
        par.paragraph_format.space_before = Pt(2)
        shade(cell, "E8EDF3")
    for i, row in enumerate(rows):
        for j, value in enumerate(row):
            cell = tbl.rows[i + 1].cells[j]
            cell.text = ""
            par = cell.paragraphs[0]
            par.alignment = (WD_ALIGN_PARAGRAPH.LEFT if (j == 0 and align_first_left)
                             else WD_ALIGN_PARAGRAPH.CENTER)
            run = par.add_run(str(value))
            run.font.size = Pt(font_size)
            par.paragraph_format.line_spacing_rule = WD_LINE_SPACING.SINGLE
            par.paragraph_format.space_after = Pt(1)
            par.paragraph_format.space_before = Pt(1)
    if col_widths:
        for j, w in enumerate(col_widths):
            for row_cells in tbl.rows:
                row_cells.cells[j].width = Cm(w)
    p("", indent=False, space_after=6, line15=False)
    return tbl


def fmt(x, nd=2):
    return f"{x:.{nd}f}"


